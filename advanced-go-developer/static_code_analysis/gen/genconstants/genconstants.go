package main

import (
	"bytes"
	"fmt"
	"go/format"

	"os"
	"log"

	"text/template"

	"golang.org/x/tools/go/packages"
)

func main() {
	const argsLen = 6

	args := os.Args[1:]
	if len(args) != argsLen {
		log.Fatal("there must be 6 args exactly")
	}

	// args = []string{"Version", "1.2.3", "Name", "myapp", "Title", "My Application"}

	type argsStruct struct{ PkgName, VersionID, Version, NameID, Name, TitleID, Title string }
	argsVals := argsStruct{
		VersionID: args[0],
		Version:   args[1],
		NameID:    args[2],
		Name:      args[3],
		TitleID:   args[4],
		Title:     args[5],
	}

	pkgs, _ := packages.Load(&packages.Config{
		Dir:  ".",
		Mode: packages.NeedName,
	})
	if len(pkgs) != 1 {
		log.Fatal(fmt.Errorf("zero or more then 1 package in the current dir"))
	}
	argsVals.PkgName = pkgs[0].Name

	tmpl, err := template.New("genconstants").Parse(`// Code generated by go generate; DO NOT EDIT.
// This file was generated by genconstants.go

package {{.PkgName}}

const (
	{{.VersionID}} = "{{.Version}}"
	{{.NameID}} = "{{.Name}}"
	{{.TitleID}} = "{{.Title}}"
)`)
	if err != nil {
		log.Fatal(err)
	}
	buf := bytes.Buffer{}

	err = tmpl.Execute(&buf, argsVals)
	if err != nil {
		log.Fatal(err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {

		log.Fatal(fmt.Errorf("go/format: %s", err))

	}

	os.WriteFile("const.go", formatted, 0o755)

}
